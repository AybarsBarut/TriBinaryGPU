LIBS = {
    "binary": dict(system="b", radix=2, levels="[0, 1]", cells=BINARY),
    "ternary": dict(system="t", radix=3, levels="[-1, 0, 1]", cells=TERNARY),
    "quaternary": dict(system="q", radix=4, levels="[0, 1, 2, 3]", cells=QUATERNARY),
}

HEADER_NOTE = """# {title}
#
# GENERATED by tools/gen_cell_libs.py. Edit the generator, then regenerate.
# Truth tables are verified against the golden models by tests/test_cells.py (L0).
#
# Every numeric hardware value is an ASSUMPTION (see docs/assumptions.md). Values marked
# confidence: low are PLACEHOLDERS with no verified source (open question Q21).
#
# Short form: `transistors: 28` expands to the record in `defaults.transistors` with value 28.
# Parameters derived at load time: area, switch_energy, leakage, delay, noise_margin_fraction.
"""

TECH = {
    "binary": dict(
        tau=("estimate", "medium", "one NAND2 stage delay; absolute scale is a normalisation, not a process measurement"),
        cost=("estimate", "medium", "standard textbook static-CMOS cell topologies, not tied to a process"),
        delay=("estimate", "medium", "logical-effort-style stage counts relative to NAND2 = 1.0, not tied to a process"),
    ),
    "ternary": dict(
        tau=("guess", "low", "same numeric value as the binary library so that differences come from cell structure; no process source"),
        cost=("guess", "low", "PLACEHOLDER rule: 2.0 x transistors of the nearest binary analog cell; no verified source (open question Q21)"),
        delay=("guess", "low", "PLACEHOLDER rule: 1.5 x delay stages of the nearest binary analog cell; no verified source (open question Q21)"),
    ),
    "quaternary": dict(
        tau=("guess", "low", "same numeric value as the binary library so that differences come from cell structure; no process source"),
        cost=("guess", "low", "PLACEHOLDER rule: 2.5 x transistors of the nearest binary analog cell; no verified source (open question Q21)"),
        delay=("guess", "low", "PLACEHOLDER rule: 1.8 x delay stages of the nearest binary analog cell; no verified source (open question Q21)"),
    ),
}


def emit(lib: str) -> str:
    spec = LIBS[lib]
    sys_ = spec["system"]
    tech = TECH[lib]
    out = [HEADER_NOTE.format(title=f"{lib} cell library")]
    out.append(f"library: {lib}")
    out.append("version: 0.1.0")
    out.append("status: reviewed   # truth tables verified (L0); numeric parameters remain flagged assumptions")
    out.append(f"system: {sys_}")
    out.append(f"radix: {spec['radix']}")
    out.append(f"levels: {spec['levels']}")
    out.append("voltage_swing:")
    out.append("  {value: 1.0, unit: V, source_type: guess, source: \"normalised swing; absolute value cancels in ratios\", confidence: medium}")
    out.append("technology:")

    def rec(name, value, unit, st, conf, src, group):
        out.append(f"  {name}: {{value: {value}, unit: {unit}, source_type: {st}, confidence: {conf}, group: {lib}_{group},")
        out.append(f"    source: \"{src}\"}}")

    rec("tau", 10.0, "ps", *[tech["tau"][0], tech["tau"][1], tech["tau"][2]], "delay_unit")
    rec("area_per_transistor", 0.1, "um2", "guess", "low", "placeholder layout density; no process source", "area_unit")
    rec("energy_per_transistor", 0.2, "fJ", "guess", "low", "placeholder switching energy per transistor per output toggle; no process source", "energy_unit")
    rec("leakage_per_transistor", 0.5, "nW", "guess", "low", "placeholder leakage per transistor; no process source", "leakage_unit")
    rec("maturity_factor", 1.0, "ratio", "guess", "low", "neutral nominal 1.0 (no maturity penalty or bonus); scaled in sensitivity analysis (open question Q7)", "maturity")
    out.append("defaults:")
    out.append("  transistors:")
    out.append(f"    {{unit: transistors, source_type: {tech['cost'][0]}, confidence: {tech['cost'][1]}, group: {lib}_cell_cost,")
    out.append(f"     source: \"{tech['cost'][2]}\"}}")
    out.append("  delay_stages:")
    out.append(f"    {{unit: tau, source_type: {tech['delay'][0]}, confidence: {tech['delay'][1]}, group: {lib}_cell_delay,")
    out.append(f"     source: \"{tech['delay'][2]}\"}}")
    out.append("cells:")
    for name, desc, ins, outs, T, D, seq, extra in spec["cells"]:
        out.append(f"  - name: {name}")
        out.append(f"    description: \"{desc}\"")
        out.append(f"    inputs: [{', '.join(ins)}]")
        out.append(f"    outputs: [{', '.join(outs)}]")
        out.append(f"    function: golden.{name}")
        out.append("    macro: false")
        out.append(f"    sequential: {str(seq).lower()}")
        if extra == "topo":
            out.append(
                f"    transistors: {{value: {T}, source_type: derived, confidence: high, range: {{min: {T}, max: {T}}},")
            out.append("      source: \"static CMOS gate topology\",")
            out.append("      notes: \"integer topology count; not varied by sensitivity analysis\"}")
        else:
            out.append(f"    transistors: {T}")
        out.append(f"    delay_stages: [{', '.join(str(d) for d in D)}]")
        if extra == "noanalog":
            out.append("    notes: \"no binary analog cell; the placeholder rule of the defaults was applied loosely, see Q21\"")
        out.append("    truth_table:")
        for ins_v, outs_v in golden.table_rows(name):
            out.append(f"      - {{in: {ins_v}, out: {outs_v}}}")
    return "\n".join(out) + "\n"


def main():
    cells = ROOT / "cells"
    cells.mkdir(exist_ok=True)
    for lib in LIBS:
        (cells / f"{lib}.yaml").write_text(emit(lib), encoding="utf-8", newline="\n")
        print("wrote", cells / f"{lib}.yaml")


if __name__ == "__main__":
    main()
